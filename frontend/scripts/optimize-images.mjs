// npm run images
// Scans public/media/images and public/media/models, converts every JPG/PNG/WEBP/AVIF to optimized WebP
// (public/media/images/optimized/<name>.webp + <name>-640.webp), skips duplicates and already-converted files,
// and writes lib/imageManifest.js. Originals are never modified.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';

const SRC_DIRS = ['public/media/images', 'public/media/models'];
const OUT = 'public/media/images/optimized';
const EXT = /\.(jpe?g|png|webp|avif)$/i;
const KNOWN = [
  [/^(photo_2026-10-24_17-01-53|hero-woman)/i, 'violet-necklace-model'],
  [/^(2G4j|ruby-set|stone-ruby)/i, 'ruby-parure-model'],
  [/^OS3Q/i, 'ruby-showroom-render'],
  [/^Ruby_and_Diamond/i, 'ruby-showcase-board'],
  [/^cobra-snake-ring/i, 'cobra-ruby-ring'],
  [/^pendant-magerit-butterfly/i, 'butterfly-pendant'],
  [/^(gia[-_]?hq)/i, 'gia-headquarters'],
  [/^FHlTYMOw/, 'ruby-faceted-oval'],
  [/^DtzAps9/, 'emerald-faceted'],
  [/^X8twiaV/, 'diamond-faceted'],
  [/^IflliZ/, 'opal-black-boulder'],
];

await fs.mkdir(OUT, { recursive: true });
const files = [];
for (const d of SRC_DIRS) {
  try { for (const f of await fs.readdir(d)) if (EXT.test(f)) files.push(path.join(d, f)); } catch {}
}
files.sort();

let names = {};
try { names = JSON.parse(await fs.readFile('lib/imageNames.json', 'utf8')); } catch {}
const nextNum = () => Object.values(names).filter((v) => /^gemstone-\d+$/.test(v)).map((v) => Number(v.slice(9))).reduce((a, b) => Math.max(a, b), 0) + 1;
const seen = new Map(), used = new Set(), manifest = [];
const stat = { found: files.length, converted: 0, skipped: 0, duplicates: 0, before: 0, after: 0 };
for (const file of files) {
  const buf = await fs.readFile(file);
  const hash = crypto.createHash('sha1').update(buf).digest('hex');
  if (seen.has(hash)) { stat.duplicates++; console.log(`dup   ${path.basename(file)} = ${seen.get(hash)}`); continue; }
  const base = path.basename(file);
  let name = KNOWN.find(([re]) => re.test(base))?.[1] || names[hash] || (names[hash] = `gemstone-${String(nextNum()).padStart(2, '0')}`);
  for (let i = 2; used.has(name); i++) name = `${name.replace(/-\d+$/, '')}-${i}`;
  used.add(name); seen.set(hash, name);

  const full = path.join(OUT, `${name}.webp`), thumb = path.join(OUT, `${name}-640.webp`);
  const srcTime = (await fs.stat(file)).mtimeMs;
  const fresh = async (p) => { try { return (await fs.stat(p)).mtimeMs >= srcTime; } catch { return false; } };
  const meta = await sharp(buf).metadata();
  if (!(await fresh(full)) || !(await fresh(thumb))) {
    await sharp(buf).rotate().resize({ width: 2000, withoutEnlargement: true }).webp({ quality: 85 }).toFile(full);
    await sharp(buf).rotate().resize({ width: 640, withoutEnlargement: true }).webp({ quality: 80 }).toFile(thumb);
    stat.converted++; console.log(`ok    ${base} -> ${name}.webp`);
  } else { stat.skipped++; console.log(`skip  ${base} (already optimized)`); }
  const out = await sharp(full).metadata();
  const bytes = (await fs.stat(full)).size;
  stat.before += buf.length; stat.after += bytes;
  manifest.push({ id: name, source: base, url: `/media/images/optimized/${name}.webp`, thumb: `/media/images/optimized/${name}-640.webp`, width: out.width, height: out.height, bytes, originalBytes: buf.length, known: KNOWN.some(([re]) => re.test(base)) });
}
await fs.writeFile('lib/imageNames.json', JSON.stringify(names, null, 2));
await fs.writeFile('lib/imageManifest.js', `// Generated by scripts/optimize-images.mjs — do not edit.\nexport const imageManifest = ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`\nfound ${stat.found} | converted ${stat.converted} | skipped ${stat.skipped} | duplicates ${stat.duplicates} | ${(stat.before / 1024).toFixed(0)} KB -> ${(stat.after / 1024).toFixed(0)} KB`);
